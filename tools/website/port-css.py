"""
Copies the approved design's stylesheet into the website, unchanged except for one fix.

  python -I tools/website/port-css.py

Reads  YelG.WebSite/docs/design/B-Ar.dc.html (its <style> holds the English rules plus the Arabic / RTL layer)
Writes YelG.WebSite/wwwroot/css/design.css

The fix: the prototype's last rule opens two nested @media blocks and never closes them, so browsers apply
it only on touch screens that also ask for reduced motion. It is split into the two rules it was meant to be:
touch screens get no sticky hover lift / shine, and reduced motion turns the card and shine motion off.
The site's own layer (classes for the prototype's inline styles) is wwwroot/css/site.css.

Colours: the prototype's palette is replaced by the official one from "YelG Brand Identity" (fonts - colors.ai):
blue #2F5EC6, light cyan #82D0DC, coral #DB8169, peach #FFD5C5 (BRAND below). The navy #0A3177 is the brand's own
(the logo text). Run with --palette to print the mapping; site.css and admin.css use the same values.
"""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'YelG.WebSite', 'docs', 'design', 'B-Ar.dc.html')
OUT = os.path.join(ROOT, 'YelG.WebSite', 'wwwroot', 'css', 'design.css')

BROKEN = ('@media (hover:none),(pointer:coarse){@media (prefers-reduced-motion: reduce){.photo:hover::after{animation:none}'
          '.svc,.svc::before,.svc .ico{transition:none}.svc:hover,.svc:focus-within{transform:none}')
FIXED = ('@media (hover:none),(pointer:coarse){.photo:hover::after{animation:none}.svc:hover,.svc:focus-within{transform:none}}\n'
         '@media (prefers-reduced-motion: reduce){.photo:hover::after{animation:none}.svc,.svc::before,.svc .ico{transition:none}'
         '.svc:hover,.svc:focus-within{transform:none}}')


# prototype colour -> brand colour, in hex and in the rgba() form the design also uses
BRAND = {
    '#1B52CC': '#2F5EC6', 'rgba(27,82,204': 'rgba(47,94,198',
    '#44D2EA': '#82D0DC', 'rgba(68,210,234': 'rgba(130,208,220',
    '#7FE3F1': '#82D0DC',
    '#DE8165': '#DB8169', 'rgba(222,129,101': 'rgba(219,129,105',
    '#FEDDC5': '#FFD5C5', 'rgba(254,221,197': 'rgba(255,213,197',
}


def brand(css):
    """The design's colours swapped for the brand's (any letter case)."""
    import re
    for old, new in BRAND.items():
        css = re.sub(re.escape(old), new, css, flags=re.IGNORECASE)
    return css


def main():
    raw = open(SRC, encoding='utf-8').read()
    css = raw[raw.index('<style>') + len('<style>'):raw.index('</style>')].strip('\n')
    if BROKEN not in css:
        raise SystemExit('The last rule of the design changed; review the fix in port-css.py.')
    css = brand(css.replace(BROKEN, FIXED))
    header = ('/* Generated by tools/website/port-css.py from docs/design/B-Ar.dc.html. Do not edit: change the design\n'
              '   or wwwroot/css/site.css (the site layer) instead. */\n')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(header + css + '\n')
    print('written', os.path.relpath(OUT, ROOT), '-', css.count('\n') + 1, 'lines')


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    if '--apply' in sys.argv:
        # one-off: give hand-written stylesheets the same palette
        for path in sys.argv[sys.argv.index('--apply') + 1:]:
            text = open(path, encoding='utf-8').read()
            open(path, 'w', encoding='utf-8', newline='').write(brand(text))
            print('palette applied to', path)
    else:
        main()
